"""표가 조회 결과 전체가 아닐 때, 그 사실을 **코드가** 공시한다.

⛔ **왜 코드인가** — 프롬프트는 이미 알려주고 있었는데도 두 번 같은 사고가 났다.

    `_build_result_preview()` 는 100행 이하·비시계열이면 상위 15행만 LLM 에 준다.
    그때 프롬프트에는 이미 두 가지가 들어간다:
        "총 86행, 아래는 그중 일부 프리뷰"
        "⚠️ 위 JSON은 전체 86행 중 일부만 담은 프리뷰입니다 …"
    그런데도 —

    붐따 #158 (2026-09-02): A급 프로모션 **86행** → 표에 15행.
        사용자: *"6월~9월에는 없어? 왜 5월만 보여줘?"*
        셀라: *"상위 15건만 표로 옮겼습니다 … 기간을 임의로 자른 제 잘못입니다."*

    붐따 #160 (2026-09-03): 9월 수출건 **16행** → 표에 8행.
        답변: *"총 **8건**이며 … 대상 국가는 독일(7건)과 노르웨이(1건)"*
        실측: 16건 · 독일 8 · **영국 7** · 노르웨이 1 — **영국이 통째로 사라졌다.**

    두 번 다 "총 N건" 이라고 **단정**했다. 잘렸다는 말은 어디에도 없었다.
    프롬프트는 확률이고 보증은 코드다 — FI 마스킹·내부 경로 마스킹과 같은 사상.

⚠️ **화면에 증거는 이미 있었다.** #160 의 답변 아래에는 `CSV로 전체 16행 받기`
   링크가 붙어 있었다 — 코드는 16행인 것을 알고 있었고 표만 8행이었다. 아는
   사실을 말하지 않은 것이 이 결함의 전부다.

⛔ **자르는 것 자체는 막지 않는다.** 프리뷰를 없애면 프롬프트가 터지고, 값 기준
   상위 N행 표본은 그 나름의 이유가 있다 (`_build_smart_preview`). 여기서는
   **자르되 자랐다고 말한다** — 미래 날짜를 막지 않고 공시하는 것과 같은 방식.
"""
from __future__ import annotations

from typing import Optional, Sequence

import structlog

logger = structlog.get_logger(__name__)

# 이 아래로는 공시하지 않는다. 프리뷰가 통째로 들어가고도 `rows_withheld` 가
# 참으로 오는 경로는 없지만, 한두 행짜리 답에 경고를 붙이면 그게 소음이 된다.
_MIN_ROWS_TO_WARN = 2


def notice(results: Optional[Sequence] = None,
           rows_withheld: bool = False) -> str:
    """표가 전체가 아니면 한 문단, 아니면 빈 문자열.

    ⛔ **표보다 먼저 말한다.** 뒤에 붙이면 후속 질문 제안·실행된 쿼리 뒤로 밀려
       정작 숫자를 읽는 사람 눈에 닿지 않는다 (물류 수량 공시가 실측으로 겪은
       것 · OP 재고 신선도 공시와 같은 규칙).
    """
    if not rows_withheld:
        return ""
    total = len(results or ())
    if total < _MIN_ROWS_TO_WARN:
        return ""
    logger.info("result_truncation_notice", rows=total)
    nl = chr(10)
    return (
        "> ⚠️ **아래 표는 조회 결과 전체가 아닙니다 — 실제로는 총 "
        + f"{total:,}행" + "입니다.**" + nl
        + "> 답변에 적힌 건수·합계·순위는 표에 실린 것만 센 값일 수 있습니다. "
        + "특히 **「총 N건」·「~뿐입니다」 같은 단정은 그대로 믿지 마세요.**" + nl
        + "> 전체는 답변 아래 CSV 링크로 받으실 수 있습니다."
        + nl + nl)


def prompt_fact(results: Optional[Sequence] = None,
                rows_withheld: bool = False) -> str:
    """서술 단계에 못 박는 사실.

    ⚠️ 보증은 `notice()` 가 한다 — 이건 공시와 **정면으로 어긋나는 문장**
       ("총 8건입니다")이 나가는 것을 줄이려는 것이다. 기존 프리뷰 경고는
       "단정하지 마세요" 까지만 말하고 **무엇을 쓰지 말라고는 안 했다.**
    """
    if not rows_withheld:
        return ""
    total = len(results or ())
    if total < _MIN_ROWS_TO_WARN:
        return ""
    nl = chr(10)
    return (
        nl + "⚠️ **표는 전체가 아니다 (확정된 사실 — 추측 금지)**: 조회 결과는 총 "
        + f"{total:,}행" + "인데 위 프리뷰에는 그중 일부만 들어 있다. "
        "⛔ **「총 N건」·「모두 N건」·「~뿐이다」 처럼 건수를 단정하지 마라.** "
        "국가·팀·항목의 **목록이 전부라고 말하지 마라** — 프리뷰에 안 실린 값이 "
        "있다. 합계·비중·순위를 만들 때도 '표에 실린 것 기준' 이라고 밝혀라. "
        "건수를 말해야 하면 조회 결과 총행수(" + f"{total:,}" + "행)를 쓰고, "
        "그것이 표에 다 실리지 않았다고 적어라." + nl)
