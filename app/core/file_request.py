# -*- coding: utf-8 -*-
"""「엑셀로 뽑아줘」에 파일을 준다. 그리고 못 준다는 거짓말을 지운다.

붐따 #161 (2026-09-03, 정다운):

    [질문] "세일즈 운영팀 정다운이 진행항 9월 etd 수출건 **엑셀로 뽑아줘**!"
    [답변] 표 8행. **파일도, 링크도 없었다.**

    [질문] "해당 면장번호에 일치하는 주문번호와 OP담당자 매칭해주고 엑셀로 뽑아줘"
    [답변] "엑셀(.xlsx) 파일 생성 | **파일 첨부·다운로드 형태의 출력은 지원하지
            않습니다** (조회 결과 표/차트까지만 가능)"

⛔ **두 번째가 거짓이다.** CSV 다운로드는 2026-08-31부터 있다
   (`sql_result_store` · `/api/sql-results/{token}/csv`). 그런데 사용자는 "안 된다"는
   말을 듣고 물러섰다 — 있는 기능을 없다고 말하는 것은 없는 기능보다 나쁘다.

⛔ **첫 번째는 조건이 좁아서 생긴 구멍이다.** 링크는 두 경우에만 붙었다:
   ① 표에서 빠진 행이 있다 ② 결과가 20행 이상.
   8행짜리 결과는 **둘 다 아니라서** 아무것도 안 붙었다. 그 조건은 "표로 다 보여줬는데
   링크까지 달면 잡음" 이라는 판단이었고 그 자체는 맞다 — **사용자가 달라고 하지
   않았을 때는.** 달라고 했으면 행이 두 줄이어도 줘야 한다.

⚠️ 우리가 주는 것은 **CSV** 다(.xlsx 가 아니다). 엑셀에서 바로 열리고 BOM 도
   붙지만, "엑셀 파일" 이라고 부르지는 않는다 — 확장자가 다르면 사용자는 그걸
   알아야 한다.
"""
from __future__ import annotations

import re

# 파일로 달라는 말. ⚠️ `뽑아줘`·`정리해줘` 만으로는 아니다 — 그건 평범한 조회
#    요청이고, 그것까지 파일 요청으로 보면 모든 답변에 링크가 붙는다.
#    **매체를 지목한 낱말**(엑셀·csv·파일·다운로드)이 있어야 한다.
_WANTS_FILE = re.compile(
    # ⚠️ `csv` 뒤에 `\b` 를 쓰지 마라 — 한글은 단어 문자라 `csv로` 에서
    #    경계가 생기지 않아 **조사가 붙는 순간 매치가 사라진다**
    #    (검색 키워드에서 조사를 먼저 떼야 했던 것과 같은 함정)
    r"엑셀|엑샐|excel|xlsx|(?<![a-z])csv(?![a-z])|스프레드시트"
    r"|파일\s*로|파일\s*형태|파일\s*으?로|파일\s*줘|파일\s*주세요"
    r"|다운\s*로드|다운받|내려\s*받|받아\s*볼|저장해\s*줘",
    re.IGNORECASE)

# ⛔ 있는 기능을 없다고 쓰는 문장. 프롬프트로도 막지만(확률) 여기서 지운다(보증).
#    `_EMPTY_DOWNLOAD_PROMISE_RE`(sql_agent)가 "요청해주세요" 라는 빈 약속을
#    지우는 것과 같은 자리의 같은 사상 — 이쪽은 **빈 거절**을 지운다.
_DENIAL = re.compile(
    r"[^\n]*(?:엑셀|excel|xlsx|csv|파일)[^\n]*"
    r"(?:지원하지\s*않|제공하지\s*않|불가능|드릴\s*수\s*없|생성할\s*수\s*없|안\s*됩니다)"
    r"[^\n]*\n?",
    re.IGNORECASE)


def wants_file(query: str) -> bool:
    """사용자가 파일로 달라고 했는가."""
    return bool(_WANTS_FILE.search(query or ""))


def strip_denials(answer: str) -> str:
    """"파일로는 못 준다" 는 문장을 지운다.

    ⚠️ 표 안의 행(`| 엑셀(.xlsx) 파일 생성 | … 지원하지 않습니다 |`)도 한 줄이라
       함께 지워진다 — 실제 사고가 표 형태였다.
    """
    return _DENIAL.sub("", answer or "")
