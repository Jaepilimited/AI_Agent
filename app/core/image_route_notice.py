# -*- coding: utf-8 -*-
"""이미지를 붙이면 사내 데이터 조회 경로를 타지 않는다 — 그 사실을 말한다.

붐따 #161 (2026-09-03, 정다운). 면장(수출신고필증) 이미지를 붙이고 물었다:

    [질문] "해당 면장번호에 일치하는 주문번호와 OP담당자 매칭해주고 엑셀로 뽑아줘"
    [답변] "이미지의 신고번호 50건은 읽어냈습니다. 다만 …
            | 신고번호 → 주문번호 매핑 테이블 | **연결된 데이터소스에
              수출신고필증/면장 정보가 없습니다** |
            | OP담당자 정보 | **담당자 배정 데이터가 조회 대상에 포함되어
              있지 않습니다** |"

⛔ **둘 다 사실이 아니다.** `export_logistics` 에 `export_declaration_number`
   (수출신고번호, 89.7% 채워짐)와 `op_manager` 가 **둘 다 있다.** 바로 다음 턴에
   사용자가 "OP담당자가 세일즈운영팀 담당자야!" 라고 알려주자 조회가 됐다.

**왜 그랬나**: `orchestrator` 는 이미지가 붙으면 **무조건 direct(vision LLM)** 로
보낸다. 그 경로는 BigQuery 스키마를 **아예 받지 않는다** — 그러니 모르는 게
당연하다. 문제는 모른다고 하지 않고 **「없습니다」라고 단정**한 것이다.

⚠️ 이 프로젝트가 반복해서 겪은 그 실패다: 성분에서 '미상'을 '미포함'으로 쓴 것,
   '없음' 에 근거를 안 적은 것, 조회실패를 '없음' 으로 센 것 — 전부 같은 얼굴이다.
   여기서는 사용자가 **있는 데이터를 없다고 듣고 물러섰다.**

⛔ 라우팅을 바꾸지는 않는다. 이미지를 읽으려면 vision 이 필요하고, 이미지 내용은
   SQL 로 옮겨지지 않는다. 대신 **무엇을 못 했는지 밝히고 다음 행동을 준다** —
   막지 않고 공시하는 그 방식이다.
"""
from __future__ import annotations

import structlog

logger = structlog.get_logger(__name__)


def notice(query: str, has_image: bool, is_data_question: bool) -> str:
    """이미지가 붙은 데이터 질문이면 한 문단, 아니면 빈 문자열.

    ⛔ 이미지 질문 **전부**에 붙이면 안 된다 — "이 사진 설명해줘" 에 데이터
       안내가 붙으면 그건 소음이고, 소음이 되면 진짜 필요할 때도 안 읽힌다.
    """
    if not has_image or not is_data_question:
        return ""
    logger.info("image_route_data_notice", query=(query or "")[:80])
    nl = chr(10)
    return (
        nl + nl
        + "> ⚠️ **이미지가 첨부된 질문은 사내 데이터 조회를 하지 않습니다.**" + nl
        + "> 위 답변은 이미지를 읽어서 쓴 것이고, 매출·물류·재고 테이블은 "
        + "조회하지 않았습니다." + nl
        + "> ⛔ 그래서 위에 **「데이터가 없습니다」라고 적혀 있어도 그것은 "
        + "「조회하지 않았다」는 뜻이지 「데이터가 없다」는 뜻이 아닙니다.**" + nl
        + "> 사내 데이터로 확인하시려면 **이미지 없이** 다시 물어봐 주세요 "
        + "(예: 수출신고번호·주문번호를 본문에 붙여넣기)."
    )


# ⛔ 프롬프트에도 넣지만 보증은 위 공시다 — vision 경로는 스키마를 못 보므로
#    "무엇이 있는지" 는 알려줄 수 없고, "없다고 단정하지 말 것" 만 말할 수 있다.
PROMPT_RULE = (
    "\n⚠️ **지금은 이미지를 읽는 경로라 사내 데이터베이스를 조회하지 않았다.**\n"
    "⛔ 사내에 어떤 데이터가 있는지 **너는 모른다.** "
    "「연결된 데이터소스에 ~가 없습니다」·「~ 데이터가 조회 대상에 포함되어 있지 "
    "않습니다」처럼 **없다고 단정하지 마라** — 실제로 있는 것을 없다고 말해 "
    "사용자가 물러선 사고가 있었다(수출신고번호·OP담당자 둘 다 실제로 있었다). "
    "대신 **「이미지가 붙은 질문은 데이터를 조회하지 않는다」**고 말하고, "
    "이미지 없이 다시 물어보도록 안내하라.\n"
)
